import type { Source, Statement } from '$lib/rdf/types';
import { db } from '$lib/storage/db';
import { getCurrentKbId } from '$lib/storage/kb-registry';
import { importSplatFile } from '$lib/storage/splat-files';
import { persistSourceBatch, prepareStatementsForWrite } from '$lib/stores/kb.svelte';
import { generationEntity, parseJob, STAGE_LABELS, verifyOutput, type GenerationJob } from './protocol';

const P = 'urn:kbase:predicate/';
const sourceIdFor = (id: string) => `generation-${id}`;

/** Stable IDs plus persistSourceBatch make replay safe, including two tabs reading one receipt. */
export function generationStatements(job: GenerationJob, mediaUrl: string): Statement[] {
  parseJob(job, job.request);
  if (!job.receipt || job.state !== 'completed') throw new Error('No checked generation result');
  const { request, receipt } = job;
  const entity = generationEntity(request.id);
  const prompt = `${entity}-prompt`;
  const sourceId = sourceIdFor(request.id);
  const rows: Statement[] = [];
  const add = (subject: string, predicate: string, value: string, iri = false) => {
    rows.push({
      id: `${sourceId}-${rows.length}`, s: { kind: 'iri', value: subject },
      p: { kind: 'iri', value: predicate }, o: { kind: iri ? 'iri' : 'literal', value },
      g: { kind: 'iri', value: `urn:kbase:source/${sourceId}` },
      sourceId, status: 'pending', confidence: 1, createdAt: Date.parse(receipt.ranAt), updatedAt: Date.parse(receipt.ranAt),
    });
  };
  const type = 'http://www.w3.org/1999/02/22-rdf-syntax-ns#type';
  const label = 'http://www.w3.org/2000/01/rdf-schema#label';
  const comment = 'http://www.w3.org/2000/01/rdf-schema#comment';
  add(prompt, type, 'urn:kbase:type/Prompt', true);
  add(prompt, label, `Prompt: ${request.prompt.slice(0, 80)}`);
  add(prompt, comment, request.prompt);
  add(entity, type, `urn:kbase:type/${{ image: 'Image', video: 'Video', splat: 'GaussianSplat' }[request.stage]}`, true);
  add(entity, label, `${STAGE_LABELS[request.stage]}: ${request.prompt.slice(0, 80)}`);
  add(entity, P + { image: 'photo', video: 'video', splat: 'splat' }[request.stage], mediaUrl);
  add(entity, P + 'made-from', request.parentId ? generationEntity(request.parentId) : prompt, true);
  if (request.parentId) add(entity, P + 'made-from', prompt, true);
  add(entity, P + 'generated-with', `${receipt.tool.name} ${receipt.tool.version}; ${receipt.models.map(m => m.file).join(', ')}`);
  add(entity, P + 'generated-seed', String(request.seed));
  add(entity, P + 'generated-at', receipt.ranAt);
  add(entity, P + 'generated-duration', `${receipt.durationS} s`);
  add(entity, comment, request.stage === 'splat'
    ? 'Generated from one image. Unseen geometry is invented, not a measurement.'
    : 'Generated by a local model; not a record of a real event.');
  for (const license of new Set([receipt.tool.license, ...receipt.models.map(m => m.license)])) {
    const licenseId = `urn:kbase:concept/license-${encodeURIComponent(license)}`;
    add(entity, 'https://schema.org/license', licenseId, true);
    add(licenseId, type, 'urn:kbase:type/License', true);
    add(licenseId, label, license);
    add(licenseId, P + 'spdx-id', license);
  }
  return rows;
}

function dataUrl(file: Blob): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result));
    reader.onerror = () => reject(new Error('Could not read generated file'));
    reader.readAsDataURL(file);
  });
}

export async function attachGeneration(job: GenerationJob, file: File): Promise<string> {
  const assertSpace = () => {
    if (getCurrentKbId() !== job.request.spaceId || db.name !== job.request.spaceId) {
      throw new Error('Return to the originating space to attach this result.');
    }
  };
  assertSpace();
  parseJob(job, job.request);
  if (!job.receipt || job.state !== 'completed') throw new Error('No checked generation result');
  await verifyOutput(await file.arrayBuffer(), job.receipt);
  assertSpace();
  const entity = generationEntity(job.request.id);
  const sourceId = sourceIdFor(job.request.id);
  if (await db.sources.get(sourceId)) return entity;
  let media: string;
  if (job.request.stage === 'splat') {
    const result = await importSplatFile(file, db);
    if (!result.ok) throw new Error(result.problems.join('; '));
    media = result.url;
  } else {
    media = await dataUrl(new Blob([file], { type: job.request.stage === 'image' ? 'image/webp' : 'video/webm' }));
  }
  assertSpace();
  const source: Source = {
    id: sourceId, title: `Generated ${job.request.stage}: ${job.request.prompt.slice(0, 80)}`,
    uri: `note://generation/${job.request.id}`, kind: 'note', ingestedAt: Date.parse(job.receipt.ranAt),
    hash: job.receipt.output.sha256,
  };
  const rows = generationStatements(job, media);
  const plan = await prepareStatementsForWrite(rows, sourceId, { origin: 'agent' });
  if (plan.statements.length !== rows.length) throw new Error('This space did not accept the generated asset statements.');
  assertSpace();
  await persistSourceBatch(source, plan);
  return entity;
}

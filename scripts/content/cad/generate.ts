/**
 * F299.1 — spec -> build123d Python. PURE and DETERMINISTIC: the same spec yields the same
 * script, byte for byte, so a part is reproducible from its record and the script is diffable.
 *
 * The script takes the output folder as argv[1] (never embedded), writes part.step and part.stl
 * there, and prints one line `RECEIPT_JSON:{...}` with the measurements taken FROM the solid
 * (volume, bounding box, versions). The TypeScript side never trusts its own arithmetic for those.
 */
import { assertValidSpec, canonicalSpecJson, type PartSpec } from './spec';

// Number literal for Python: finite and plain, never exponent form for the sizes we accept.
const n = (v: number) => String(Number(v.toFixed(6)));

function bracketBody(p: Record<string, number>): string {
  return `# L-bracket: base plate on z in [0, t], upright wall on y in [d - t, d]; x is centred.
w, h, d, t = ${n(p.width_mm)}, ${n(p.height_mm)}, ${n(p.depth_mm)}, ${n(p.thickness_mm)}
hole_d, hole_n, fil = ${n(p.hole_diameter_mm)}, ${n(p.hole_count)}, ${n(p.fillet_mm)}

with BuildPart() as bp:
    with BuildSketch(Plane.YZ):
        with BuildLine():
            Polyline((0, 0), (d, 0), (d, h), (d - t, h), (d - t, t), (0, t), close=True)
        make_face()
    extrude(amount=w / 2, both=True)
    if fil > 0:
        inner = bp.edges().filter_by(Axis.X).filter_by_position(Axis.Y, d - t - 0.01, d - t + 0.01).filter_by_position(Axis.Z, t - 0.01, t + 0.01)
        fillet(inner, radius=fil)
    if hole_n > 0:
        pitch = w / hole_n
        for i in range(int(hole_n)):
            x = -w / 2 + pitch * (i + 0.5)
            with Locations((x, (d - t) / 2, 0)):
                Cylinder(radius=hole_d / 2, height=t * 3, mode=Mode.SUBTRACT)
part = bp.part`;
}

function enclosureBody(p: Record<string, number>): string {
  return `# Enclosure body: open top, rounded vertical corners, a rebate at the rim for a lid to sit in.
w, d, h = ${n(p.width_mm)}, ${n(p.depth_mm)}, ${n(p.height_mm)}
wall, r, lip = ${n(p.wall_mm)}, ${n(p.corner_radius_mm)}, ${n(p.lip_height_mm)}

with BuildPart() as bp:
    with BuildSketch(Plane.XY):
        RectangleRounded(w, d, r)
    extrude(amount=h)
    with BuildSketch(Plane.XY.offset(wall)):
        RectangleRounded(w - 2 * wall, d - 2 * wall, max(r - wall, 0.1))
    extrude(amount=h, mode=Mode.SUBTRACT)
    with BuildSketch(Plane.XY.offset(h - lip)):
        RectangleRounded(w - wall, d - wall, max(r - wall / 2, 0.1))
    extrude(amount=lip, mode=Mode.SUBTRACT)
part = bp.part`;
}

export function specToBuild123d(spec: PartSpec): string {
  assertValidSpec(spec);
  const body = spec.kind === 'bracket' ? bracketBody(spec.params) : enclosureBody(spec.params);
  return `# Generated by scripts/content/cad/generate.ts from this part spec. Do not hand-edit:
# ${canonicalSpecJson(spec)}
import json, os, sys
import build123d
from build123d import *

${body}

if not part.is_valid:
    raise SystemExit("build123d produced an invalid solid")

# Sit the part on z = 0, centred on x and y, so every output shares one origin convention.
bb = part.bounding_box()
part = Pos(-(bb.min.X + bb.max.X) / 2, -(bb.min.Y + bb.max.Y) / 2, -bb.min.Z) * part
bb = part.bounding_box()

out = sys.argv[1]
os.makedirs(out, exist_ok=True)
export_step(part, os.path.join(out, "part.step"))
export_stl(part, os.path.join(out, "part.stl"))

try:
    ocp_version = __import__("OCP").__version__
except Exception:
    ocp_version = "unknown"
print("RECEIPT_JSON:" + json.dumps({
    "volume_mm3": part.volume,
    "bbox_mm": {"x": bb.size.X, "y": bb.size.Y, "z": bb.size.Z},
    "build123d": build123d.__version__,
    "ocp": ocp_version,
    "python": sys.version.split()[0],
}, sort_keys=True))
`;
}

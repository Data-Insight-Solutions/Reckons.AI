// ── a small statement builder ─────────────────────────────────────────────────

type Extra = Partial<Statement>;
class Builder {
  statements: Statement[] = [];
  constructor(readonly source: Source) {}
  add(s: string, p: string, o: Term, status: Statement['status'], extra: Extra = {}): void {
    const sT = iri(s), pT = iri(p);
    const key = `${this.source.id}|${s}|${p}|${o.kind}:${o.value}`;
    this.statements.push({
      id: `rex-${createHash('sha256').update(key).digest('hex').slice(0, 16)}`,
      s: sT, p: pT, o, g: iri(`urn:kbase:source/${this.source.id}`), sourceId: this.source.id,
      confidence: status === 'confirmed' ? 1 : 0.8, status, createdAt: AT, updatedAt: AT, ...extra,
    });
  }
  /** type + label (+ comment) of a node, all held. */
  node(id: string, type: string, label: string, comment?: string, status: Statement['status'] = 'confirmed', extra: Extra = {}): string {
    const s = KB + id;
    this.add(s, RDF_TYPE, iri(TYPE + type), status, extra);
    this.add(s, RDFS_LABEL, lit(label), status, extra);
    if (comment) this.add(s, RDFS_COMMENT, lit(comment), status, extra);
    return s;
  }
}

const source = (id: string, title: string): Source => ({ id, title, uri: `note://sample/${id}`, kind: 'turtle', ingestedAt: AT, trustLevel: 'review' });
const render = (b: Builder, header: string[]): string =>
  toTurtleFull(b.statements, [b.source], { header: header.join('\n') }).replace(/^# generated .*\n/m, '');


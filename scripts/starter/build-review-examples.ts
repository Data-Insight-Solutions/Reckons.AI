/** FIXTURE worker and done records, written to a temp directory. Not this machine's queue. */
function writeJobFixture(dir: string): void {
  const L = (o: unknown) => JSON.stringify(o);
  const lines = (a: unknown[]) => a.map(L).join('\n') + '\n';
  writeFileSync(path.join(dir, 'queue.jsonl'), lines([
    { id: 'q-scan', name: 'room-scan', cwd: '/example', argv: [], addedAt: '2026-11-10T08:00:00.000Z', gpu: true, gpuIndex: 0 },
    { id: 'q-describe', name: 'describe-entities', cwd: '/example', argv: [], addedAt: '2026-11-10T08:05:00.000Z', after: ['room-scan'] },
  ]));
  writeFileSync(path.join(dir, 'current.json'), L([{ name: 'room-scan', pid: process.pid, started: '2026-11-10T08:30:00.000Z' }]));
  writeFileSync(path.join(dir, 'worker.json'), L({ state: 'working', held: ['weekly-summary: 6 unreviewed proposals'] }));
  writeFileSync(path.join(dir, 'circuits.json'), L({ 'flaky-export': { count: 3, signature: 'exit=1|export failed: no space left in fixture' } }));
  const done: unknown[] = [];
  for (let i = 0; i < 26; i++) { // one job with MORE than 20 runs: 20 are kept as nodes, the rest are a count
    const day = String(1 + Math.floor(i / 3)).padStart(2, '0');
    done.push({ id: `lc${String(i).padStart(2, '0')}`, name: 'sched:link-check', cwd: '/example', argv: [], addedAt: `2026-11-${day}T00:00:00.000Z`, finishedAt: `2026-11-${day}T0${i % 3}:00:00.000Z`, outcome: i % 7 === 0 ? 'failed' : 'passed', exitCode: i % 7 === 0 ? 1 : 0 });
  }
  for (let i = 0; i < 3; i++) done.push({ id: `fe${i}`, name: 'flaky-export', cwd: '/example', finishedAt: `2026-11-0${i + 5}T12:00:00.000Z`, outcome: 'failed', exitCode: 1 });
  done.push({ id: 'ws1', name: 'weekly-summary', cwd: '/example', finishedAt: '2026-11-08T07:00:00.000Z', outcome: 'passed', exitCode: 0 });
  done.push({ id: 'rs1', name: 'room-scan', cwd: '/example', finishedAt: '2026-11-07T10:00:00.000Z', outcome: 'passed', exitCode: 0, result: { kind: 'scan-attach', space: 'workshop-example', contentId: '0123456789abcdef0123456789abcdef.spz' } });
  writeFileSync(path.join(dir, 'queue.done.jsonl'), lines(done));
}

export async function buildJobs(): Promise<string> {
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'review-jobs-'));
  try {
    writeJobFixture(tmp);
    writeFileSync(path.join(tmp, 'jobs.ttl'), JOBS_TTL);
    writeFileSync(path.join(tmp, 'schedules.ttl'), SCHED_TTL);
    const out = path.join(tmp, 'device', 'job-records.ttl');
    execFileSync('npx', ['tsx', path.join(ROOT, 'scripts', 'agent', 'queue-to-space.ts'), '--device', `--dir=${tmp}`, `--jobs=${path.join(tmp, 'jobs.ttl')}`, `--schedules=${path.join(tmp, 'schedules.ttl')}`, `--device-out=${out}`, `--out=${path.join(tmp, 'plan.ttl')}`], { cwd: ROOT, stdio: 'pipe' });
    // Add the reviewer's node to what the script wrote: import it, append, and serialize it the same way.
    const imported = await importTurtleFull(readFileSync(out, 'utf8'));
    const b = new Builder(source('review-example-jobs', 'Example: job records (fixture)'));
    const check = b.node('rx-what-to-check', 'Concept', 'What to check',
      'Demonstrates F269.1 (every local job detailed in This device). THIS IS A FIXTURE, not this machine: invented jobs and made-up run records, generated by scripts/agent/queue-to-space.ts --device from fixture worker and done files. '
      + '1) Find the job nodes: each carries its state (running, queued, held with a reason, given-up). "room-scan" should be running, "describe-entities" queued and waiting on it, "weekly-summary" held, "flaky-export" given-up. '
      + '2) Open "link-check": it ran 26 times, so it should show its 20 newest runs as nodes and a count for the older six. '
      + '3) Open a failed run: it should show how it ended. The "room-scan" run that made a splat names its output id. '
      + '4) Weakness to know: the real This device space does not exist yet (F269), and nothing schedules this script, so the real device file is not here.');
    b.add(check, KP + 'demonstrates', lit('F269.1'), 'confirmed');
    const statements = imported.statements.map((s) => ({ ...s }));
    return toTurtleFull([...statements, ...b.statements], [...imported.sources, b.source], {
      header: ['Reckons.AI — Example space: job records (F269.1).', 'GENERATED by scripts/starter/build-review-examples.ts from fixture worker and done records, through scripts/agent/queue-to-space.ts --device.', 'A fixture: the jobs and runs are invented and say nothing about any machine.'].join('\n'),
      kbStableId: 'b1b1b1b1-2c2c-4d3d-8e4e-5f6f708192b5',
    }).replace(/^# generated .*\n/m, '');
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

// ── main ─────────────────────────────────────────────────────────────────────

async function main(): Promise<void> {
  const files: [string, string | Buffer][] = [
    [OUT_PROPOSALS, buildProposals()],
    [OUT_SCAN, buildScan()],
    [OUT_JOBS, await buildJobs()],
    [path.join(SPLAT_DIR, 'scan-linked.ply'), plyBytes(400, 'grid')],
    [path.join(SPLAT_DIR, 'scan-unlinked.ply'), plyBytes(120, 'ring')],
  ];
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, content] of files) {
    const rel = path.relative(ROOT, file);
    const cur = existsSync(file) ? readFileSync(file) : null;
    const next = typeof content === 'string' ? Buffer.from(content) : content;
    if (check) { if (!cur || !cur.equals(next)) { console.error(`build-review-examples --check: ${rel} is stale`); stale++; } continue; }
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, next);
    console.log(`wrote ${rel} (${next.length} bytes)`);
  }
  if (check) { if (stale) { console.error('Run: npx tsx scripts/starter/build-review-examples.ts'); process.exit(1); } console.log('build-review-examples --check: up to date'); }
}

if (process.argv[1] && process.argv[1].endsWith('build-review-examples.ts')) void main();

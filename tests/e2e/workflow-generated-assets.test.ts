import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'fs';
import { execFileSync } from 'child_process';
import { join } from 'path';
import { clearStorage, waitForApp } from './helpers';
import { boxTarget } from '../visual/workflow-harness';
import { demoRecorder, isDemoRender } from './demo-recorder';
import { playStory, type StepException } from './story-runner';
import type { UnifiedStory } from '../../src/lib/rdf/story-steps';

/**
 * TEST WORKFLOW: GENERATED ASSETS (F58.9.4 / kb:splat-e2e-workflow) — a picture made from a prompt,
 * then a clip and a Gaussian splat made from that picture, all by local models, shown on the nodes
 * of their own space, with one splat set as the space's background.
 *
 * THE STEPS ARE NOT WRITTEN HERE. They are the ktype:TestStep triples of test:Workflow-GeneratedAssets
 * in static/docs-testing.ttl, the same list that draws the diagram and the sections of
 * /docs/testing/workflow-generated-assets. THE STORY RUNNER PLAYS THEM (F300.3, tests/e2e/story-runner.ts):
 * it performs each step's story:action literals and checks its story:expect literals, and the demo
 * recorder (npm run demo:story) is the same call with recording on. What a story cannot declare yet
 * stays below as a NAMED EXCEPTION per step (`exceptions`, each with its reason); the test fails if
 * an exception names a step the story does not have (the F34.2 pattern).
 *
 * WHAT IT CANNOT DO: run the models. CI has no GPU. The pictures, clips and splats were generated by
 * `npm run gen:assets` on a machine that has the tools, and committed with a receipt each. So the
 * generation steps check, in the browser, that the file the app shows is byte-for-byte the one its
 * receipt describes (SHA-256), that the receipt says its independent check accepted it, and that
 * the app shows it. The page says the same.
 */

const WORKFLOW_ID = 'generated-assets';
const CAPTURE_DIR = process.env.WORKFLOW_CAPTURE_DIR ?? '';

const story = JSON.parse(
  execFileSync('npx', ['tsx', 'scripts/workflow-steps.ts', `--story=${WORKFLOW_ID}`], { encoding: 'utf8' }),
) as UnifiedStory;

/** Collapse the notification stack so it does not cover the graph in the screenshots. */
async function quietToasts(page: Page) {
  const collapse = page.getByRole('button', { name: /^collapse notifications$/i });
  if (await collapse.isVisible().catch(() => false)) await collapse.click();
}

async function previewAll(page: Page) {
  const previews = page.locator('.overlay-group', { hasText: /previews/i });
  await previews.locator('button.chip').first().click();
  await page.getByRole('button', { name: 'preview all', exact: true }).click();
  await page.keyboard.press('Escape');
}

/**
 * NAMED EXCEPTIONS (F300.3). The steps "picture", "video", "splat" and "background" (3 to 6) are declared in the graph in full (select the node, open its asset,
 * the receipt check, the served file, its width, the viewer status, the background and the splat counter), so they
 * need no code. What a story cannot declare yet stays here as code with its reason, so the gap stays visible:
 *   - open-example: landing on the graph and then visiting the Spaces tab inside one step (a second page
 *     visit after a click that navigates on its own) is not an action sequence the runner can order safely.
 *   - see-pipeline: switching previews on goes through chips and buttons with no testid, and "at least three
 *     previews are on screen" is not an expectation kind (the count depends on where the layout puts nodes).
 *   - video: showing a frame from the middle of the clip means seeking it; there is no seek action.
 */
const exceptions: Record<string, StepException> = {
  'open-example': {
    why: 'landing on the graph then visiting the Spaces tab inside one step is a second page visit after a click that navigates on its own',
    before: async (page) => {
      const card = page.getByTestId('starter-card-generated-assets');
      await expect(card).toBeVisible({ timeout: 10_000 });
      await expect(card).toContainText(/open as a space/i);
    },
    perform: async (page) => {
      // Opening switches to the new space and LANDS ON THE GRAPH. It used to reload the About page,
      // which looked like nothing had happened (Matt, 2026-10-14), and this test hid that by going to
      // the Spaces tab on its own. So it now checks where the person actually ends up.
      await page.waitForURL((url) => url.pathname === '/', { timeout: 15_000 });
      await expect(page.locator('main canvas').first()).toBeVisible({ timeout: 15_000 });
      await page.goto('/kb');
      await expect(page.locator('.kb-entry.current').first()).toContainText(/generated assets/i, { timeout: 10_000 });
    },
  },

  'see-pipeline': {
    why: 'preview toggling and the on-screen preview count have no testid or expectation kind; the splat counter is declared in the background step',
    perform: async (page, snap) => {
      await page.waitForTimeout(3_000);
      await quietToasts(page);
      await previewAll(page);
      // Previews are drawn for the nodes in view; where each node lands is up to the force layout, so
      // count rather than name them. Splats are counted by the 3D graph itself, below.
      await expect.poll(() => page.getByRole('button', { name: /open asset for (image|video|splat):/i }).count(), { timeout: 15_000 })
        .toBeGreaterThanOrEqual(3);
      // Both node splats have loaded into the 3D graph (the canvas reports "loaded/failed").
      // The showcase music box is over the Gaussian budget and waits to be loaded (step load-showcase).
      await expect(page.getByTestId('graph-canvas')).toHaveAttribute('data-splats', '2/0', { timeout: 30_000 });
      await page.waitForTimeout(1_500);
      await snap(page.locator('main canvas').first());
    },
  },

  video: {
    why: 'showing a frame from the middle of the clip needs a seek, which is not an action kind',
    perform: async (page) => {
      // Show a frame from the middle of the clip rather than the first one, which is the picture itself.
      const video = page.getByTestId('asset-video');
      await expect.poll(() => video.evaluate((v) => (v as HTMLVideoElement).readyState >= HTMLMediaElement.HAVE_METADATA)).toBe(true);
      await video.evaluate((v) => { (v as HTMLVideoElement).currentTime = 1.5; });
      await page.waitForTimeout(600);
    },
  },
};

test.beforeEach(async ({ page }) => {
  // The screenshots are 1280x800; a demo render keeps its own 1280x720 at 1.5x (playwright.demo.config.ts).
  if (!isDemoRender()) await page.setViewportSize({ width: 1280, height: 800 });
  await clearStorage(page);
  await waitForApp(page);
});

test('every named exception belongs to a step of the story', () => {
  const inGraph = new Set(story.steps.map((s) => s.id));
  for (const id of Object.keys(exceptions)) expect(inGraph.has(id), `exception "${id}" names no step in the story`).toBe(true);
  // Every step is either declared enough to run alone or has a named exception explaining what is code.
  for (const s of story.steps) expect(s.actions.length > 0 || exceptions[s.id], `step "${s.id}" has neither an action nor a named exception`).toBeTruthy();
});

test('the steps with no code are declared in the graph, with expectations', () => {
  for (const id of ['picture', 'splat', 'background']) {
    const st = story.steps.find((x) => x.id === id)!;
    expect(st.actions.length > 0 && st.expects.length > 0, `step "${id}" declares its actions and expectations`).toBe(true);
  }
});

test(`${story.label}`, async ({ page }) => {
  const record = demoRecorder(page); // F275.3: a no-op unless npm run demo:story is recording
  test.setTimeout(record.active ? 600_000 : 180_000);
  if (CAPTURE_DIR) mkdirSync(CAPTURE_DIR, { recursive: true });
  const outcomes = await playStory(page, story, {
    record,
    exceptions,
    onSnap: async (step, target) => {
      if (!CAPTURE_DIR) return;
      await target.evaluate((el) => el.scrollIntoView({ block: 'center' }));
      await page.waitForTimeout(900);
      const cleanup = await boxTarget(page, target, step.target?.label ?? step.title);
      const png = await page.screenshot({ fullPage: false });
      await cleanup();
      writeFileSync(join(CAPTURE_DIR, `${String(step.order).padStart(2, '0')}-${step.id}.png`), png);
    },
  });
  expect(outcomes.map((o) => o.id), 'the runner played every step of the story, in order').toEqual(story.steps.map((s) => s.id));
});
